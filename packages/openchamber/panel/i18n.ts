/** 全部语言字典（导出用于测试完整性校验） */
export const dicts: Record<LocaleKey, Record<string, string>> = {
  en, 'zh-CN': zhCN, 'zh-TW': zhTW, de, fr, uk, es, 'pt-BR': ptBR, ko, pl, ja, tr,
};

/** 支持的 locale（小写，用于归一化匹配） */
const SUPPORTED = new Set(Object.keys(dicts).map(k => k.toLowerCase()));

/** 当前 locale（默认简体中文，onReady 后由宿主 locale 覆盖） */
let current: LocaleKey = 'zh-CN';

/**
 * 将宿主 locale 归一化为支持的 locale 键
 * @param raw - 宿主 locale（如 zh-CN、de-DE、pt-BR）
 * @returns 支持的 locale 键；无法识别时回退英文
 */
export function resolveLocale(raw: string): LocaleKey {
  const lower = raw.toLowerCase();
  if (SUPPORTED.has(lower)) {
    return Object.keys(dicts).find(k => k.toLowerCase() === lower) as LocaleKey;
  }
  const base = lower.split(/[-_]/)[0];
  // 中文变体：tw/hk/hant → 繁体，其余 → 简体
  if (base === 'zh') {
    if (lower.includes('tw') || lower.includes('hk') || lower.includes('hant')) return 'zh-TW';
    return 'zh-CN';
  }
  if (SUPPORTED.has(base)) {
    return Object.keys(dicts).find(k => k.toLowerCase() === base) as LocaleKey;
  }
  // 带地区后缀的语言（如 pt → pt-BR）
  const prefixed = Object.keys(dicts).find(k => k.toLowerCase().startsWith(`${base}-`));
  return (prefixed as LocaleKey) ?? 'en';
}

/**
 * 设置语言
 * @param locale - 宿主 locale，自动归一化到支持的 12 种语言之一
 */
export function setLocale(locale: string): void {
  current = resolveLocale(locale);
}

/** 获取当前 locale 键 */
export function getLang(): LocaleKey {
  return current;
}

/**
 * 翻译文案
 * @param key - 文案键
 * @param params - 占位符参数（替换 {name}）
 * @returns 对应语言文案；缺失时回退简体中文，再缺失回退 key 本身
 */
export function t(key: string, params?: Record<string, string | number>): string {
  let text = dicts[current][key] ?? zhCN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
